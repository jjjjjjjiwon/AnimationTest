/*

// 1. 시스템 초기화 및 관리

Awake() - StageManager를 싱글톤으로 설정

OnSceneLoaded() - 새로운 스테이지(씬)가 로드될 때마다 맵에 배치된 포탈(Portal) 오브젝트를 찾아 연결

OnDestroy() - 객체가 파괴될 때 씬 로드 이벤트 연결을 해제하여 메모리 누수를 막습니다.


2. 스테이지 시작 및 흐름 컨트롤

Update() - 씬 진행 관련

StartStage() - 새로운 스테이지 데이터를 주입받고, 해당 씬으로 이동

ResetStageProgress() - 새로운 스테이지가 시작되기 전, 기존의 킬 수, 타이머, 클리어 여부를 0으로 초기화


3. 적 소환 시스템

CheckSpawnConditions() - 소환 대기 명단을 돌면서 "지금 나올 적이 있는가?"를 판단하는 컨트롤 타워

IsConditionMet() - 특정 적의 소환 조건(시간 경과, 킬 수 달성 등)이 현재 데이터와 일치하는지 검사

SpawnEnemy() - 소환이 확정된 적의 ID(일반/보스)를 확인하여 실제 월드에 적을 생성


4. 클리어 판정 및 연출

NotifyEnemyKilled() - 적이 죽을 때마다 호출되어 킬 수를 올리고, "모두 처치" 혹은 "목표 킬 수" 달성 여부를 확인

NotifyBossKilled() - 보스급 적이 죽었을 때 호출되어 즉시 스테이지 클리어 여부를 결정

OnStageCleared() - 모든 조건이 달성되면 호출되며, **클리어 연출(코루틴)**을 시작하고 포탈을 활성화

ClearSequenceRoutine() - 슬로우 모션, 클리어 UI 표시, 카메라 연출 등 시간 흐름에 따른 연출을 담당합니다.


5. 기타

ParseClearCondition() - 스테이지 시작 시, 해당 스테이지의 클리어 조건 데이터가 올바른지 확인하고 시스템이 인식할 수 있는 형태로 변환

*/


