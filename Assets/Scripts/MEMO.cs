/*

Start(): 컴포넌트를 연결하고, 게임 데이터 매니저(RuntimeManager)가 준비되었는지 확인 후 초기화를 시작합니다.

WaitForRuntimeManager(): 매니저가 아직 생성 안 됐을 경우, 생성될 때까지 기다려주는 비상 대기실입니다.

InitializePlayer(): 스테이트 머신(상태기)을 생성하고, 모든 공격/이동 상태를 등록하며 플레이를 시작할 준비를 마칩니다.

Update(): 매 프레임 플레이어의 키보드/마우스 입력을 실시간으로 감시합니다.

FixedUpdate(): 현재 플레이어의 상태(Idle, Move 등)에 맞는 물리 연산과 로직을 실행합니다.

CanOpenUI(): 현재 가만히 있거나 걷는 중인지 확인하여, 아이템창 같은 UI를 열어도 되는 안전한 상황인지 판별합니다.

AddStatPoints(int amount): 보상으로 받은 포인트를 실제 시스템 데이터(RuntimeManager.playerStats)에 영구적으로 추가합니다.

HandleInput(): 눌린 키에 따라 회피를 할지, 공격을 시도할지 분기점을 나누는 중간 관리자입니다.

GetInputType(): 클릭, Q, E, R 등 여러 공격 키 중 정확히 어떤 버튼이 눌렸는지를 데이터(Enum)로 변환합니다.

TakeStunDamage(): (미정) 적의 무거운 공격에 맞았을 때 **'스턴 게이지'**를 깎아 행동 불능 상태로 만들 준비를 합니다.

RecoverStunGauge(): (미정) 스턴에 걸린 후 혹은 일정 시간이 지난 후 스턴 게이지를 다시 차오르게 관리합니다.

HitboxOn(): 애니메이션의 특정 프레임에서 **"지금 내보낼 콤보 스킬"**의 데미지 판정을 칼에 주입하고 켭니다.

HitboxOff(): 휘두르는 동작이 끝나면 칼의 데미지 판정을 꺼서 허공에 데미지가 남지 않게 합니다.

ForceDisableHitbox(): 공격 도중 적에게 맞아 공격이 끊겼을 때, 켜져 있던 칼 판정을 즉시 강제로 끕니다.

TryAttack(): 이미 공격 중이면 다음 콤보를 예약하고, 가만히 있었다면 첫 번째 공격(소켓)을 시작합니다.

TakeDamage(): 체력을 깎고 UI를 갱신하며, 죽지 않았다면 '피격(움찔)' 상태로 강제 전환합니다.

Die(): 체력이 0이 되었을 때 호출되어, 상태를 **'사망'**으로 바꾸고 조작을 차단합니다.

TryDodge(): 회피 버튼을 눌렀을 때 현재 회피 가능한 상태인지 확인한 후 '회피' 상태로 전환합니다.

CanDodge(): 설정된 **쿨타임(초)**이 지났는지 계산하여 다시 회피할 수 있는지 판단합니다.

*/

